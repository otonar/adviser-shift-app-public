-- =====================
-- シフト枠にタイトルを追加
-- =====================
-- 研修の枠が並んだとき、日付と時間だけではどれが何の研修か見分けられなかった。
-- 備考（note）は長い補足にも使うため、一覧に出す短い名前として title を分ける。
-- 当日の枠にも付けられる（任意）。
--
-- 列の追加のみで既存の行は NULL のまま。コード側は title が無くても動くように
-- してある（未入力なら INSERT/UPDATE に title を含めない）ので、コードを先に
-- 反映しても壊れない。ただし適用するまではタイトルを入力した保存が失敗する。
ALTER TABLE shift_slots
  ADD COLUMN IF NOT EXISTS title TEXT;                -- 枠のタイトル（任意・50文字以内はアプリ側で検証）
